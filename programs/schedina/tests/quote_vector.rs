//! Generates and checks `fixtures/schedina/quote_vector.json`: the exact bytes of the
//! desk-signed quote and cash-out messages (C3), one worked signature each, and the
//! instruction data around them, for the desk (2.A) and the app (2.E) to reproduce.
//! The test fails if the file disagrees with the program's encoding; regenerate with
//! `SCHEDINA_WRITE_FIXTURES=1 cargo test --test quote_vector` from `programs/`.
//! It also submits the worked quote and cash-out to the program in LiteSVM.

mod common;

use anchor_lang::{prelude::Pubkey, InstructionData};
use common::*;
use schedina::{CashOutMsg, QuoteLeg, QuoteMsg, CASHOUT_TAG, QUOTE_TAG};
use serde_json::{json, Value};
use solana_keypair::Keypair;
use solana_signer::Signer;

const SIGNER_SEED: [u8; 32] = [7; 32];
const USER_SEED: [u8; 32] = [9; 32];
const NONCE: u64 = 7;
const QUOTE_EXPIRES_AT: i64 = 1_793_213_000;
const EXPIRES_AT: i64 = 1_793_213_040;

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn sha(s: &str) -> [u8; 32] {
    solana_sha256_hasher::hash(s.as_bytes()).to_bytes()
}

struct LegIn {
    symbol: &'static str,
    game_id: &'static str,
    start_ts: i64,
    side: u8,
    price_u: u64,
    m1_ppm: u32,
}

const LEGS: [LegIn; 2] = [
    LegIn {
        symbol: "NBA_26OCT28_PHIIND_ML.PHI",
        game_id: "nba-phi-ind-2026-10-28",
        start_ts: 1_793_228_400,
        side: 0,
        price_u: 695_000,
        m1_ppm: 50_000,
    },
    LegIn {
        symbol: "NBA_26OCT28_CHADET_ML.CHA",
        game_id: "nba-cha-det-2026-10-28",
        start_ts: 1_793_230_200,
        side: 1,
        price_u: 412_000,
        m1_ppm: 50_000,
    },
];

fn worked_quote() -> QuoteMsg {
    let legs: Vec<QuoteLeg> = LEGS
        .iter()
        .map(|l| QuoteLeg {
            symbol_hash: sha(l.symbol),
            game_id_hash: sha(l.game_id),
            start_ts: l.start_ts,
            side: l.side,
            price_u: l.price_u,
            m1_ppm: l.m1_ppm,
        })
        .collect();
    let stake_u = 10 * USDC;
    let payout =
        schedina::math::payout(stake_u, legs.iter().map(|l| (l.m1_ppm, l.price_u))).unwrap();
    QuoteMsg {
        tag: QUOTE_TAG,
        program_id: schedina::ID,
        legs,
        stake_u,
        odds_offered_u: schedina::math::odds(payout, stake_u).unwrap(),
        quote_expires_at: QUOTE_EXPIRES_AT,
    }
}

fn user() -> Keypair {
    Keypair::new_from_array(USER_SEED)
}

fn worked_cashout() -> CashOutMsg {
    CashOutMsg {
        tag: CASHOUT_TAG,
        program_id: schedina::ID,
        ticket: ticket_pda(&user().pubkey(), NONCE),
        c_u: 12_000_000,
        ts: QUOTE_EXPIRES_AT + 3_600,
    }
}

fn field(name: &str, offset: &str, size: usize, ty: &str) -> Value {
    json!({"field": name, "offset": offset, "size": size, "type": ty})
}

fn build() -> Value {
    let signer = Keypair::new_from_array(SIGNER_SEED);
    let q = worked_quote();
    let qmsg = borsh(&q);
    let qsig = sign(&signer, &qmsg);
    let floor = q.odds_offered_u * 97 / 100;
    let open_data = schedina::instruction::OpenPending {
        nonce: NONCE,
        min_payout_per_unit_u: floor,
        expires_at: EXPIRES_AT,
        is_tip: false,
        copied_from: None,
    }
    .data();

    let c = worked_cashout();
    let cmsg = borsh(&c);
    let csig = sign(&signer, &cmsg);
    let cash_data = schedina::instruction::CashOut { quote: c.clone() }.data();
    assert_eq!(&cash_data[8..], cmsg.as_slice());

    let legs_in: Vec<Value> = LEGS
        .iter()
        .zip(&q.legs)
        .map(|(l, ql)| {
            json!({
                "symbol": l.symbol, "symbol_hash": hex(&ql.symbol_hash),
                "game_id": l.game_id, "game_id_hash": hex(&ql.game_id_hash),
                "start_ts": l.start_ts, "side": l.side, "price_u": l.price_u, "m1_ppm": l.m1_ppm,
            })
        })
        .collect();

    json!({
        "_doc": "Desk-signed messages of the schedina program (L1 contract C3), generated by programs/schedina/tests/quote_vector.rs, which fails if this file drifts. Integers little-endian; each message is the borsh encoding of the instruction argument (QuoteMsg of open_pending, CashOutMsg of cash_out) and is the exact byte string the desk signs with ed25519. Offsets are bytes from the start of the message; n = number of legs, i = leg index (0-based).",
        "program_id": schedina::ID.to_string(),
        "ed25519_program_id": schedina::ED25519_PROGRAM_ID.to_string(),
        "signer_seed_hex": hex(&SIGNER_SEED),
        "signer_pubkey": signer.pubkey().to_string(),
        "verification": "Transaction shape: [..., Ed25519Program verify, schedina instruction] (wallets may prepend compute-budget or guard instructions; the verify must be IMMEDIATELY before the schedina instruction). The verify carries exactly one signature and all three instruction-index fields are 0xFFFF (public key, signature and message inside the verify itself), i.e. solana's new_ed25519_instruction_with_signature(msg, sig, pubkey); the hex below is that instruction's data. Data layout: [num_signatures u8 = 1, padding u8 = 0, signature_offset u16 = 48, signature_instruction_index u16 = 0xFFFF, public_key_offset u16 = 16, public_key_instruction_index u16 = 0xFFFF, message_data_offset u16 = 112, message_data_size u16, message_instruction_index u16 = 0xFFFF, public key (32), signature (64), message]. The public key must be Config.quote_signer. open_pending takes no quote argument: it decodes the verified message as a QuoteMsg (no trailing bytes), so the client copies the desk's signed bytes untouched. cash_out takes the CashOutMsg as its argument and requires the verified message to equal its borsh encoding.",
        "quote": {
            "size": "77 + 85*n",
            "layout": [
                field("tag", "0", 17, "bytes, ASCII \"schedina/quote/v1\""),
                field("program_id", "17", 32, "pubkey"),
                field("n (borsh Vec length)", "49", 4, "u32"),
                field("legs[i].symbol_hash", "53 + 85*i", 32, "sha256 of the Pascal symbol (UTF-8)"),
                field("legs[i].game_id_hash", "53 + 85*i + 32", 32, "sha256 of display_attributes.game_page.game_id (UTF-8)"),
                field("legs[i].start_ts", "53 + 85*i + 64", 8, "i64, Unix seconds"),
                field("legs[i].side", "53 + 85*i + 72", 1, "u8, 0 long, 1 short"),
                field("legs[i].price_u", "53 + 85*i + 73", 8, "u64, ask-side quote price p_i, micro-units"),
                field("legs[i].m1_ppm", "53 + 85*i + 81", 4, "u32, per-leg margin"),
                field("stake_u", "53 + 85*n", 8, "u64, micro-USDC"),
                field("odds_offered_u", "53 + 85*n + 8", 8, "u64, micro-units"),
                field("quote_expires_at", "53 + 85*n + 16", 8, "i64, Unix seconds; open_pending needs now <= quote_expires_at"),
            ],
            "inputs": {
                "legs": legs_in,
                "stake_u": q.stake_u,
                "odds_offered_u": q.odds_offered_u,
                "quote_expires_at": q.quote_expires_at,
            },
            "message_hex": hex(&qmsg),
            "message_sha256_hex": hex(&solana_sha256_hasher::hash(&qmsg).to_bytes()),
            "signature_hex": hex(&qsig),
            "ed25519_ix_hex": hex(&ed25519_ix(&qmsg, &qsig, &signer.pubkey()).data),
            "open_pending": {
                "args": "nonce u64, min_payout_per_unit_u u64, expires_at i64, is_tip bool (u8), copied_from Option<Pubkey> (0 = None, or 1 + 32 bytes); the quote is the verify instruction's message, not an argument",
                "nonce": NONCE,
                "min_payout_per_unit_u": floor,
                "expires_at": EXPIRES_AT,
                "is_tip": false,
                "copied_from": null,
                "ix_data_hex": hex(&open_data),
            },
        },
        "cash_out": {
            "size": 99,
            "layout": [
                field("tag", "0", 19, "bytes, ASCII \"schedina/cashout/v1\""),
                field("program_id", "19", 32, "pubkey"),
                field("ticket", "51", 32, "pubkey, the Ticket PDA [\"ticket\", user, nonce u64 LE]"),
                field("c_u", "83", 8, "u64, micro-USDC paid, <= Ticket.payout_u"),
                field("ts", "91", 8, "i64, desk Unix seconds; valid while |now - ts| <= 30"),
            ],
            "inputs": {
                "user": user().pubkey().to_string(),
                "nonce": NONCE,
                "ticket": c.ticket.to_string(),
                "c_u": c.c_u,
                "ts": c.ts,
            },
            "message_hex": hex(&cmsg),
            "signature_hex": hex(&csig),
            "ed25519_ix_hex": hex(&ed25519_ix(&cmsg, &csig, &signer.pubkey()).data),
            "cash_out_ix_data_hex": hex(&cash_data),
            "message_offset_in_ix_data": 8,
            "cash_out_args": "quote: CashOutMsg (the 99-byte message itself)",
        },
    })
}

fn fixture_path() -> String {
    concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../fixtures/schedina/quote_vector.json"
    )
    .to_string()
}

#[test]
fn fixture_matches_the_program_encoding() {
    let want = build();
    let path = fixture_path();
    if std::env::var("SCHEDINA_WRITE_FIXTURES").is_ok() {
        let mut s = serde_json::to_string_pretty(&want).unwrap();
        s.push('\n');
        std::fs::write(&path, s).unwrap();
    }
    let got: Value = serde_json::from_str(
        &std::fs::read_to_string(&path)
            .expect("quote_vector.json missing: run with SCHEDINA_WRITE_FIXTURES=1"),
    )
    .unwrap();
    assert!(
        got == want,
        "{path} disagrees with the program's encoding; regenerate with SCHEDINA_WRITE_FIXTURES=1 cargo test --test quote_vector"
    );
}

#[test]
fn offsets_match_the_bytes() {
    let q = worked_quote();
    let m = borsh(&q);
    let n = q.legs.len();
    assert_eq!(m.len(), 77 + 85 * n);
    assert_eq!(&m[0..17], b"schedina/quote/v1");
    assert_eq!(&m[17..49], schedina::ID.as_ref());
    assert_eq!(
        u32::from_le_bytes(m[49..53].try_into().unwrap()) as usize,
        n
    );
    for (i, l) in q.legs.iter().enumerate() {
        let b = 53 + 85 * i;
        assert_eq!(&m[b..b + 32], &l.symbol_hash);
        assert_eq!(&m[b + 32..b + 64], &l.game_id_hash);
        assert_eq!(
            i64::from_le_bytes(m[b + 64..b + 72].try_into().unwrap()),
            l.start_ts
        );
        assert_eq!(m[b + 72], l.side);
        assert_eq!(
            u64::from_le_bytes(m[b + 73..b + 81].try_into().unwrap()),
            l.price_u
        );
        assert_eq!(
            u32::from_le_bytes(m[b + 81..b + 85].try_into().unwrap()),
            l.m1_ppm
        );
    }
    let e = 53 + 85 * n;
    assert_eq!(
        u64::from_le_bytes(m[e..e + 8].try_into().unwrap()),
        q.stake_u
    );
    assert_eq!(
        u64::from_le_bytes(m[e + 8..e + 16].try_into().unwrap()),
        q.odds_offered_u
    );
    assert_eq!(
        i64::from_le_bytes(m[e + 16..e + 24].try_into().unwrap()),
        q.quote_expires_at
    );

    let c = worked_cashout();
    let m = borsh(&c);
    assert_eq!(m.len(), 99);
    assert_eq!(&m[0..19], b"schedina/cashout/v1");
    assert_eq!(&m[19..51], schedina::ID.as_ref());
    assert_eq!(&m[51..83], c.ticket.as_ref());
    assert_eq!(u64::from_le_bytes(m[83..91].try_into().unwrap()), c.c_u);
    assert_eq!(i64::from_le_bytes(m[91..99].try_into().unwrap()), c.ts);
}

/// The worked vectors are accepted by the program: the quote opens a pending (compact
/// form), the crank mints it, and the worked cash-out pays out.
#[test]
fn worked_vectors_run_on_chain() {
    let mut h = Harness::new();
    h.quote_signer = Keypair::new_from_array(SIGNER_SEED);
    let params = default_params(h.crank.pubkey(), h.quote_signer.pubkey());
    let ix = h.ix_init_config(&h.deployer.pubkey(), h.authority.pubkey(), params);
    ok(h.send_deployer(ix));
    let funder = h.user(HOUSE);
    ok(h.fund_vault(&funder, HOUSE));

    let kp = user();
    h.svm.airdrop(&kp.pubkey(), 10_000_000_000).unwrap();
    let usdc = Pubkey::new_unique();
    h.write_token_account(&usdc, &kp.pubkey(), 100 * USDC);
    let u = User { kp, usdc };

    let q = worked_quote();
    h.set_time(EXPIRES_AT - 40);
    let s = h.quote_signer.insecure_clone();
    let floor = q.odds_offered_u * 97 / 100;
    ok(h.open_with(&u, NONCE, &q, floor, EXPIRES_AT, false, &s));
    ok(h.finalize(&u, NONCE, vec![0, 0], 1_000_000));

    let c = worked_cashout();
    h.set_time(c.ts);
    ok(h.cash_out_with(&u, &c, &s));
    assert_eq!(h.balance(&u.usdc), 90 * USDC + c.c_u);
}
